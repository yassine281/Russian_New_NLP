"""Генерация итогового отчета по лабораторной работе № 1 на русском языке."""

from pathlib import Path
from typing import Any, Dict, List, Sequence

import config
from models.frequency import FrequencyEntry


class ReportGenerator:
    """Формирует полный академический отчет с таблицами и ответами на контрольные вопросы."""

    def __init__(self, reports_dir: Path = config.REPORTS_DIR) -> None:
        self.reports_dir = Path(reports_dir)
        self.reports_dir.mkdir(parents=True, exist_ok=True)

    def generate(
        self,
        stats: Dict[str, Any],
        tok_comparisons: List[Dict[str, Any]],
        morph_rows: List[Dict[str, str]],
        top_30: Sequence[FrequencyEntry],
        zipf_data: Dict[str, Any],
        heaps_data: Dict[str, Any],
    ) -> Path:
        out_path = self.reports_dir / "academic_report.md"

        morph_table = "\n".join(
            f"| {r['word']} | {r['pymorphy3']} | {r['spacy']} | {r['snowball']} |"
            for r in morph_rows
        )
        top30_table = "\n".join(
            f"| {e.rank} | {e.word} | {e.count} |" for e in top_30
        )

        report_text = f"""# Лабораторная работа № 1
## Тема: Предобработка текста и базовый лингвистический анализ русскоязычного новостного корпуса

**Выполнил:** Mouri Yassine (Моури Яссин)

---

### 1. Цель и задачи работы
Освоить методы сбора корпуса с русскоязычных новостных сайтов (`lenta.ru`, `ria.ru`, `gazeta.ru`, `tass.ru`), провести очистку, токенизацию, лемматизацию (`Pymorphy3`, `spaCy`), стемминг (`NLTK SnowballStemmer`), удаление стоп-слов и частотный анализ (законы Ципфа и Хипса).

---

### 2. Характеристики собранного корпуса (Задание 1)
- **Число собранных статей:** {stats['total_articles']}
- **Общий объём корпуса (слов):** {stats['total_words']}
- **Средняя длина статьи:** {stats['average_words']:.1f} слов
- **Размер уникального словаря после очистки:** {stats['vocab_size']} лемм

---

### 3. Сравнение токенизаторов (Задание 2)
Проведено сравнение `Simple (.split())`, `NLTK (word_tokenize)` и `spaCy (ru_core_news_sm)`.
**Вывод:** токенизатор `spaCy` и `NLTK` корректно отделяют знаки препинания от слов, а `spaCy` лучше всего сохраняет русские дефисные конструкции (`по-новому`, `санкт-петербург`).

---

### 4. Сравнение лемматизации и стемминга (Задание 3)
| Слово | Pymorphy3 | spaCy | SnowballStemmer |
|---|---|---|---|
{morph_table}

**Вывод:** Лемматизаторы (`Pymorphy3` и `spaCy`) приводят слово к осмысленной словарной форме (`бегущий` -> `бежать`), тогда как стеммер просто отсекает окончания (`красивая` -> `красив`).

---

### 5. Удаление стоп-слов (Задание 4)
- **До фильтрации:** {stats['tokens_before_stopwords']} токенов
- **После фильтрации:** {stats['tokens_after_stopwords']} токенов
- **Удалено:** {stats['tokens_removed']} токенов ({stats['percentage_removed']:.1f}%)

---

### 6. Частотный анализ и законы Ципфа и Хипса (Задание 5)
- **Закон Ципфа:** наклон регрессии `slope = {zipf_data['slope']:.3f}` ($R^2 = {zipf_data['r_squared']:.4f}$).
- **Закон Хипса:** коэффициент `k = {heaps_data['k']:.3f}`, показатель роста словаря `beta = {heaps_data['beta']:.3f}` ($R^2 = {heaps_data['r_squared']:.4f}$).

#### Топ-30 самых частотных слов корпуса:
| Ранг | Слово | Частота |
|---|---|---|
{top30_table}

---

### 7. Ответы на контрольные вопросы
1. **Что такое парсинг? Какие инструменты используются?**
   Автоматическое извлечение данных с веб-страниц с помощью `requests`, `BeautifulSoup4`, `lxml`, `Scrapy`, `Selenium`.
2. **Какие этические нормы нужно соблюдать при парсинге?**
   Соблюдать `robots.txt`, выдерживать паузу между запросами (`0.5` сек), не перегружать сервер и указывать источник.
3. **Чем отличается токенизация от лемматизации?**
   Токенизация разбивает текст на отдельные слова/токены, а лемматизация приводит каждое слово к его начальной словарной форме.
4. **В чём разница между лемматизацией и стеммингом?**
   Лемматизация использует словарь и морфологию для возврата начальной формы слова (`бегущий` -> `бежать`), а стемминг механически отсекает окончания (`красивая` -> `красив`).
5. **Какие инструменты предобработки русского текста вы знаете?**
   `Pymorphy3`, `spaCy` (`ru_core_news_sm`), `NLTK` (`SnowballStemmer`), `Yandex Mystem`, `Natasha`.
6. **Что такое стоп-слова? Зачем их удалять?**
   Служебные слова (предлоги, союзы, частицы, местоимения), не несущие тематического смысла. Их удаляют для снижения информационного шума.
7. **Сформулируйте закон Ципфа. Как он проявляется на вашем корпусе?**
   Частота слова обратно пропорциональна его рангу ($f(r) \\approx C / r$). На логарифмическом графике корпуса образуется прямая с отрицательным наклоном `{zipf_data['slope']:.3f}`.
8. **Сформулируйте закон Хипса. Как он проявляется на вашем корпусе?**
   Зависимость размера словаря $V$ от объема текста $N$ описывается формулой $V(N) = k \\cdot N^\\beta$. На корпусе наблюдается сублинейный рост с $\\beta = {heaps_data['beta']:.3f}$.
"""
        with open(out_path, "w", encoding="utf-8") as fh:
            fh.write(report_text)
        return out_path